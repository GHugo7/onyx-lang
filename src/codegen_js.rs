//! JavaScript backend: AST + analysis -> a single self-contained .js file.

use crate::ast::*;
use crate::checker::{fn_key, lambda_key, method_key, Analysis, CallKind, Recv, Type};
use crate::diagnostics::SourceMap;
use std::collections::HashMap;

pub struct Options<'a> {
    /// Used to report the file and line of a failed `expect`.
    pub sources: &'a SourceMap,
    /// Emit the `check` blocks and run them instead of `main`.
    pub test_mode: bool,
}

const RUNTIME: &str = include_str!("runtime.js");

/// Names that would clash with JavaScript syntax or with globals the generated code uses.
const JS_RESERVED: &[&str] = &[
    "arguments", "async", "await", "case", "class", "debugger", "default", "delete", "do", "enum",
    "eval", "export", "extends", "finally", "function", "implements", "import", "instanceof", "let",
    "new", "null", "package", "private", "protected", "public", "static", "super", "switch",
    "this", "throw", "try", "typeof", "undefined", "var", "void", "with", "yield", "NaN",
    "Infinity", "Math", "Map", "Array", "Date", "Promise", "Object", "String", "Number",
    "Symbol", "Error", "console", "process", "require", "globalThis",
];

fn js_name(name: &str) -> String {
    if JS_RESERVED.contains(&name) {
        format!("{name}$")
    } else {
        // Names from imported modules look like `module.name`.
        name.replace(['.', '~'], "$")
    }
}

fn prop(name: &str) -> String {
    if matches!(name, "constructor" | "__proto__" | "prototype") {
        format!("{name}$")
    } else {
        name.to_string()
    }
}

fn js_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 || c == '\u{2028}' || c == '\u{2029}' => {
                out.push_str(&format!("\\u{:04x}", c as u32))
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Where the value of a `catch` expression goes.
enum Sink<'e> {
    Var(String),
    Assign(&'e Expr, AssignOp),
    Return,
    Discard,
}

struct Gen<'a> {
    an: &'a Analysis,
    opts: &'a Options<'a>,
    out: String,
    indent: usize,
    tmp: usize,
    /// Number of `await`s emitted so far; used to decide whether a thunk must be async.
    awaits: usize,
    /// How many `or`/`catch` subjects enclose the expression being generated,
    /// within the current function. A `?` in there has to get past them.
    handlers: usize,
    /// Onyx variable name -> JavaScript name, innermost scope last.
    scopes: Vec<HashMap<String, String>>,
}

pub fn generate(program: &Program, an: &Analysis, opts: &Options) -> String {
    let mut g = Gen { an, opts, out: String::new(), indent: 0, tmp: 0, awaits: 0, handlers: 0, scopes: vec![HashMap::new()] };
    g.out.push_str("// Generated by the Onyx compiler. Do not edit.\n");
    g.out.push_str(RUNTIME);
    g.out.push_str("\n(async () => {\n\"use strict\";\n");

    // Globals are visible everywhere, so register their names first.
    for item in &program.items {
        if let Item::Global(Stmt { kind: StmtKind::Let { name, .. }, .. }) = item {
            g.scopes[0].insert(name.clone(), js_name(name));
        }
    }
    for item in &program.items {
        if let Item::Struct(s) = item {
            g.strukt(s);
        }
    }
    for item in &program.items {
        if let Item::Fn(f) = item {
            let is_async = an.async_keys.contains(&fn_key(&f.name));
            let header = format!("{}function {}", if is_async { "async " } else { "" }, js_name(&f.name));
            g.function(&header, f);
        }
    }
    let globals: Vec<String> = program
        .items
        .iter()
        .filter_map(|item| match item {
            Item::Global(Stmt { kind: StmtKind::Let { name, .. }, .. }) => Some(js_name(name)),
            _ => None,
        })
        .collect();
    if !globals.is_empty() {
        g.line(&format!("let {};", globals.join(", ")));
    }
    if opts.test_mode {
        g.line("const $tests = [];");
        for item in &program.items {
            if let Item::Check { name, body, .. } = item {
                g.line(&format!("$tests.push([{}, async () => {{", js_string(name)));
                g.block_body(body);
                g.line("}]);");
            }
        }
    }
    // Everything that runs is inside `$rt.run`, which reports failures properly.
    g.line("await $rt.run(async () => {");
    g.indent += 1;
    for item in &program.items {
        if let Item::Global(Stmt { kind: StmtKind::Let { name, init, .. }, .. }) = item {
            let value = g.expr(init);
            g.line(&format!("{} = {value};", js_name(name)));
        }
    }
    g.line(if opts.test_mode { "await $rt.runTests($tests);" } else { "await main();" });
    g.indent -= 1;
    g.line("});");
    g.out.push_str("})();\n");
    g.out
}

impl<'a> Gen<'a> {
    fn line(&mut self, text: &str) {
        for _ in 0..self.indent {
            self.out.push_str("  ");
        }
        self.out.push_str(text);
        self.out.push('\n');
    }

    fn fresh(&mut self, prefix: &str) -> String {
        self.tmp += 1;
        format!("${prefix}{}", self.tmp)
    }

    fn ty(&self, e: &Expr) -> &Type {
        self.an.types.get(&e.id).unwrap_or(&Type::Unknown)
    }

    // ---- scopes ----

    /// Declares an Onyx variable and returns its JavaScript name, renaming it
    /// when it would shadow a variable of an enclosing scope (JavaScript's
    /// `let x = x + 1` does not see the outer `x`).
    fn declare(&mut self, name: &str) -> String {
        let base = js_name(name);
        let taken = self.scopes.iter().any(|s| s.values().any(|v| v == &base));
        let js = if taken { format!("{}{}", base, self.fresh("")) } else { base };
        self.scopes.last_mut().unwrap().insert(name.to_string(), js.clone());
        js
    }

    fn resolve(&self, name: &str) -> String {
        if name == "self" {
            return "this".to_string();
        }
        self.scopes
            .iter()
            .rev()
            .find_map(|s| s.get(name))
            .cloned()
            .unwrap_or_else(|| js_name(name))
    }

    // ---- declarations ----

    fn strukt(&mut self, s: &StructDecl) {
        self.line(&format!("class {} {{", js_name(&s.name)));
        self.indent += 1;
        self.line(&format!("static $name = {};", js_string(&s.name)));
        // Which fields hold floats (see `float_shape`).
        let floats: Vec<String> = self.an.structs[&s.name]
            .fields
            .iter()
            .filter_map(|(field, ty)| float_shape(ty).map(|shape| format!("{}: {shape}", prop(field))))
            .collect();
        if !floats.is_empty() {
            self.line(&format!("static $floats = {{ {} }};", floats.join(", ")));
        }
        let params: Vec<String> = (0..s.fields.len()).map(|i| format!("${i}")).collect();
        self.line(&format!("constructor({}) {{", params.join(", ")));
        self.indent += 1;
        for (i, f) in s.fields.iter().enumerate() {
            self.line(&format!("this.{} = ${i};", prop(&f.name)));
        }
        self.indent -= 1;
        self.line("}");
        for m in &s.methods {
            let is_async = self.an.async_keys.contains(&method_key(&s.name, &m.name));
            let header = format!("{}{}", if is_async { "async " } else { "" }, prop(&m.name));
            self.function(&header, m);
        }
        self.indent -= 1;
        self.line("}");
    }

    fn function(&mut self, header: &str, f: &FnDecl) {
        self.scopes.push(HashMap::new());
        let params: Vec<String> = f.params.iter().map(|p| self.declare(&p.name)).collect();
        self.line(&format!("{header}({}) {{", params.join(", ")));
        self.indent += 1;
        for stmt in &f.body.stmts {
            self.stmt(stmt);
        }
        self.indent -= 1;
        self.line("}");
        self.scopes.pop();
    }

    /// Emits the statements of a block, indented, in a fresh scope (no braces).
    fn block_body(&mut self, block: &Block) {
        self.scopes.push(HashMap::new());
        self.indent += 1;
        for stmt in &block.stmts {
            self.stmt(stmt);
        }
        self.indent -= 1;
        self.scopes.pop();
    }

    // ---- statements ----

    fn stmt(&mut self, stmt: &Stmt) {
        match &stmt.kind {
            StmtKind::Let { name, init, .. } => {
                if let ExprKind::Catch { .. } = &init.kind {
                    // Declare first so the sink can assign from both branches.
                    let js = self.declare(name);
                    self.line(&format!("let {js};"));
                    self.catch(init, Sink::Var(js));
                } else {
                    let value = self.expr(init);
                    let js = self.declare(name);
                    self.line(&format!("let {js} = {value};"));
                }
            }
            StmtKind::Assign { target, op, value } => {
                if let ExprKind::Catch { .. } = &value.kind {
                    self.catch(value, Sink::Assign(target, *op));
                } else {
                    let v = self.expr(value);
                    let code = self.assign(target, *op, &v);
                    self.line(&code);
                }
            }
            StmtKind::Expr(e) => {
                if let ExprKind::Catch { .. } = &e.kind {
                    self.catch(e, Sink::Discard);
                } else {
                    let code = self.expr(e);
                    self.line(&format!("{code};"));
                }
            }
            StmtKind::If { .. } => self.if_stmt(stmt, "if"),
            StmtKind::While { cond, body } => {
                let c = self.expr(cond);
                self.line(&format!("while ({c}) {{"));
                self.block_body(body);
                self.line("}");
            }
            StmtKind::For { var, iter, body, .. } => self.for_stmt(var, iter, body),
            StmtKind::Return(value) => match value {
                Some(v) if matches!(v.kind, ExprKind::Catch { .. }) => self.catch(v, Sink::Return),
                Some(v) => {
                    let code = self.expr(v);
                    self.line(&format!("return {code};"));
                }
                None => self.line("return;"),
            },
            StmtKind::Break => self.line("break;"),
            StmtKind::Continue => self.line("continue;"),
            StmtKind::Fail(value) => {
                let v = self.expr(value);
                self.line(&format!("$rt.fail({v});"));
            }
            StmtKind::Fork(body) => {
                let saved = self.awaits;
                let handlers = std::mem::take(&mut self.handlers);
                self.line("$rt.fork(async () => {");
                self.block_body(body);
                self.line("});");
                self.handlers = handlers;
                self.awaits = saved;
            }
            StmtKind::Send { chan, value } => {
                let c = self.expr(chan);
                let v = self.expr(value);
                self.awaits += 1;
                self.line(&format!("await {c}.send({v});"));
            }
            StmtKind::Block(body) => {
                self.line("{");
                self.block_body(body);
                self.line("}");
            }
        }
    }

    fn if_stmt(&mut self, stmt: &Stmt, keyword: &str) {
        let StmtKind::If { cond, then, els } = &stmt.kind else { return };
        let c = self.expr(cond);
        self.line(&format!("{keyword} ({c}) {{"));
        self.block_body(then);
        match els.as_deref() {
            Some(Stmt { kind: StmtKind::If { .. }, .. }) => {
                // The condition of an `else if` may need statements of its own
                // (it cannot here: conditions are plain expressions), so chain directly.
                let els = els.as_deref().unwrap();
                self.if_stmt(els, "} else if");
            }
            Some(Stmt { kind: StmtKind::Block(body), .. }) => {
                self.line("} else {");
                self.block_body(body);
                self.line("}");
            }
            _ => self.line("}"),
        }
    }

    fn for_stmt(&mut self, var: &str, iter: &Expr, body: &Block) {
        self.scopes.push(HashMap::new());
        match self.ty(iter).clone() {
            Type::Range => {
                let (lo, hi) = match &iter.kind {
                    ExprKind::Range { lo, hi } => (self.expr(lo), self.expr(hi)),
                    _ => {
                        let r = self.fresh("r");
                        let value = self.expr(iter);
                        self.line(&format!("const {r} = {value};"));
                        (format!("{r}[0]"), format!("{r}[1]"))
                    }
                };
                let end = self.fresh("n");
                let v = self.declare(var);
                self.line(&format!("for (let {v} = {lo}, {end} = {hi}; {v} < {end}; {v}++) {{"));
            }
            Type::Map(..) => {
                let m = self.expr(iter);
                let v = self.declare(var);
                self.line(&format!("for (const {v} of ({m}).keys()) {{"));
            }
            Type::Chan(_) => {
                let c = self.fresh("c");
                let got = self.fresh("v");
                let ch = self.expr(iter);
                let v = self.declare(var);
                self.awaits += 1;
                self.line(&format!("for (const {c} = {ch};;) {{"));
                self.indent += 1;
                self.line(&format!("const {got} = await {c}.recvOpt();"));
                self.line(&format!("if ({got} === $rt.CLOSED) break;"));
                self.line(&format!("const {v} = {got};"));
                self.indent -= 1;
            }
            _ => {
                let list = self.expr(iter);
                let v = self.declare(var);
                self.line(&format!("for (const {v} of {list}) {{"));
            }
        }
        self.block_body(body);
        self.line("}");
        self.scopes.pop();
    }

    /// Builds the statement that stores `value` (already JavaScript) into `target`.
    fn assign(&mut self, target: &Expr, op: AssignOp, value: &str) -> String {
        let is_int = self.ty(target) == &Type::Int;
        let combine = |current: &str| -> String {
            match op {
                AssignOp::Set => value.to_string(),
                AssignOp::Add => format!("{current} + {value}"),
                AssignOp::Sub => format!("{current} - {value}"),
                AssignOp::Mul => format!("{current} * {value}"),
                AssignOp::Div if is_int => format!("$rt.idiv({current}, {value})"),
                AssignOp::Div => format!("{current} / {value}"),
            }
        };
        match &target.kind {
            ExprKind::Index { obj, index } => {
                let o = self.expr(obj);
                let i = self.expr(index);
                if matches!(self.ty(obj), Type::Map(..)) {
                    format!("{o}.set({i}, {});", combine(&format!("$rt.mapGet({o}, {i})")))
                } else {
                    format!("$rt.setIdx({o}, {i}, {});", combine(&format!("$rt.idx({o}, {i})")))
                }
            }
            _ => {
                let t = self.expr(target);
                format!("{t} = {};", combine(&t))
            }
        }
    }

    /// `call() catch err { ... }`, lowered to try/catch.
    fn catch(&mut self, e: &Expr, sink: Sink) {
        let ExprKind::Catch { expr, name, body, .. } = &e.kind else { return };
        let has_value = self.an.catch_values.contains(&e.id);
        self.handlers += 1;
        let inner = self.expr(expr);
        self.handlers -= 1;
        let caught = self.fresh("e");
        self.line("try {");
        self.indent += 1;
        self.sink(&sink, &inner);
        self.indent -= 1;
        self.line(&format!("}} catch ({caught}) {{"));
        self.scopes.push(HashMap::new());
        self.indent += 1;
        let err = self.declare(name);
        self.line(&format!("const {err} = $rt.caught({caught});"));
        let (last, rest) = match body.stmts.split_last() {
            Some((last, rest)) if has_value => (Some(last), rest),
            _ => (None, &body.stmts[..]),
        };
        for stmt in rest {
            self.stmt(stmt);
        }
        if let Some(Stmt { kind: StmtKind::Expr(value), .. }) = last {
            let v = self.expr(value);
            self.sink(&sink, &v);
        }
        self.indent -= 1;
        self.scopes.pop();
        self.line("}");
    }

    fn sink(&mut self, sink: &Sink, value: &str) {
        let code = match sink {
            Sink::Var(name) => format!("{name} = {value};"),
            Sink::Assign(target, op) => self.assign(target, *op, value),
            Sink::Return => format!("return {value};"),
            Sink::Discard => format!("{value};"),
        };
        self.line(&code);
    }

    // ---- expressions ----

    fn await_(&mut self, code: String) -> String {
        self.awaits += 1;
        format!("(await {code})")
    }

    /// Converts an expression to its display string.
    fn to_str(&mut self, e: &Expr) -> String {
        let code = self.expr(e);
        match self.ty(e) {
            Type::Str => code,
            Type::Float => format!("$rt.fstr({code})"),
            ty => match float_shape(&ty) {
                Some(shape) => format!("$rt.str({code}, {shape})"),
                None => format!("$rt.str({code})"),
            },
        }
    }

    fn exprs(&mut self, list: &[Expr]) -> String {
        let parts: Vec<String> = list.iter().map(|e| self.expr(e)).collect();
        parts.join(", ")
    }

    fn expr(&mut self, e: &Expr) -> String {
        match &e.kind {
            // Parentheses keep a negative literal from merging with a preceding `-`.
            ExprKind::Int(n) if *n < 0 => format!("({n})"),
            ExprKind::Int(n) => n.to_string(),
            ExprKind::Float(n) if *n < 0.0 => format!("({n:?})"),
            ExprKind::Float(n) => format!("{n:?}"),
            ExprKind::Bool(b) => b.to_string(),
            ExprKind::Str(parts) => {
                if let [StrPart::Lit(s)] = parts.as_slice() {
                    return js_string(s);
                }
                let pieces: Vec<String> = parts
                    .iter()
                    .map(|p| match p {
                        StrPart::Lit(s) => js_string(s),
                        StrPart::Expr(inner) => self.to_str(inner),
                    })
                    .collect();
                format!("({})", pieces.join(" + "))
            }
            ExprKind::Ident(name) => self.resolve(name),
            ExprKind::List(items) => format!("[{}]", self.exprs(items)),
            ExprKind::Map(entries) => {
                let pairs: Vec<String> = entries
                    .iter()
                    .map(|(k, v)| {
                        let k = self.expr(k);
                        let v = self.expr(v);
                        format!("[{k}, {v}]")
                    })
                    .collect();
                format!("new Map([{}])", pairs.join(", "))
            }
            ExprKind::StructLit { name, fields, .. } => {
                // Constructor arguments follow the declaration order of the fields.
                let order: Vec<String> = self.an.structs[name].fields.iter().map(|(n, _)| n.clone()).collect();
                let mut args = Vec::new();
                for field in &order {
                    if let Some(init) = fields.iter().find(|f| &f.name == field) {
                        args.push(self.expr(&init.value));
                    }
                }
                format!("new {}({})", js_name(name), args.join(", "))
            }
            ExprKind::Unary { op, expr } => {
                let v = self.expr(expr);
                match op {
                    UnOp::Neg => format!("(-{v})"),
                    UnOp::Not => format!("(!{v})"),
                }
            }
            ExprKind::Binary { op, lhs, rhs } => {
                let l = self.expr(lhs);
                let r = self.expr(rhs);
                let both_int = self.ty(lhs) == &Type::Int && self.ty(rhs) == &Type::Int;
                let primitive =
                    |t: &Type| matches!(t, Type::Int | Type::Float | Type::Bool | Type::Str);
                let simple_eq = primitive(self.ty(lhs)) && primitive(self.ty(rhs));
                match op {
                    BinOp::Div if both_int => format!("$rt.idiv({l}, {r})"),
                    BinOp::Mod if both_int => format!("$rt.imod({l}, {r})"),
                    BinOp::Eq if simple_eq => format!("({l} === {r})"),
                    BinOp::NotEq if simple_eq => format!("({l} !== {r})"),
                    BinOp::Eq => format!("$rt.eq({l}, {r})"),
                    BinOp::NotEq => format!("(!$rt.eq({l}, {r}))"),
                    _ => format!("({l} {} {r})", op.symbol()),
                }
            }
            ExprKind::Call { callee, args } => self.call(e, callee, args),
            ExprKind::Field { obj, name, .. } => {
                let o = self.expr(obj);
                format!("{o}.{}", prop(name))
            }
            ExprKind::Index { obj, index } => {
                let o = self.expr(obj);
                let i = self.expr(index);
                match self.ty(obj) {
                    Type::Map(..) => format!("$rt.mapGet({o}, {i})"),
                    Type::Str => format!("$rt.strIdx({o}, {i})"),
                    _ => format!("$rt.idx({o}, {i})"),
                }
            }
            ExprKind::Lambda { params, body, .. } => {
                let is_async = self.an.async_keys.contains(&lambda_key(e.id));
                let saved_awaits = self.awaits;
                let saved_handlers = std::mem::take(&mut self.handlers);
                let saved_out = std::mem::take(&mut self.out);
                self.scopes.push(HashMap::new());
                let names: Vec<String> = params.iter().map(|p| self.declare(&p.name)).collect();
                self.indent += 1;
                for stmt in &body.stmts {
                    self.stmt(stmt);
                }
                self.indent -= 1;
                self.scopes.pop();
                let body_code = std::mem::replace(&mut self.out, saved_out);
                self.awaits = saved_awaits;
                self.handlers = saved_handlers;
                let close = "  ".repeat(self.indent);
                format!(
                    "({}({}) => {{\n{body_code}{close}}})",
                    if is_async { "async " } else { "" },
                    names.join(", ")
                )
            }
            // An error is an exception that travels up by itself. Inside the
            // subject of an `or` or a `catch`, though, `?` still means "leave
            // the function": the error is wrapped so that it gets past them.
            ExprKind::Try(inner) if self.handlers == 0 => self.expr(inner),
            ExprKind::Try(inner) => {
                let depth = self.handlers;
                let before = self.awaits;
                let value = self.expr(inner);
                if self.awaits > before {
                    self.await_(format!("$rt.passAsync({depth}, async () => {value})"))
                } else {
                    format!("$rt.pass({depth}, () => {value})")
                }
            }
            ExprKind::Or { expr, default } => {
                let before = self.awaits;
                self.handlers += 1;
                let value = self.expr(expr);
                self.handlers -= 1;
                let fallback = self.expr(default);
                if self.awaits > before {
                    self.await_(format!("$rt.orAsync(async () => {value}, async () => {fallback})"))
                } else {
                    format!("$rt.or(() => {value}, () => {fallback})")
                }
            }
            // The checker only accepts `catch` at statement level, handled in `stmt`.
            ExprKind::Catch { expr, .. } => self.expr(expr),
            ExprKind::Recv(chan) => {
                let c = self.expr(chan);
                self.await_(format!("{c}.recv()"))
            }
            ExprKind::ChanNew { cap, .. } => {
                let cap = cap.as_ref().map(|c| self.expr(c)).unwrap_or_else(|| "0".into());
                format!("new $rt.Chan({cap})")
            }
            ExprKind::Range { lo, hi } => {
                let lo = self.expr(lo);
                let hi = self.expr(hi);
                format!("[{lo}, {hi}]")
            }
        }
    }

    fn call(&mut self, e: &Expr, callee: &Expr, args: &[Expr]) -> String {
        let kind = self.an.calls.get(&e.id).cloned().unwrap_or(CallKind::Dynamic);
        match kind {
            CallKind::Fn(name) => {
                let code = format!("{}({})", js_name(&name), self.exprs(args));
                if self.an.async_keys.contains(&fn_key(&name)) {
                    self.await_(code)
                } else {
                    code
                }
            }
            CallKind::Method(strukt, name) => {
                let ExprKind::Field { obj, .. } = &callee.kind else { return String::new() };
                let o = self.expr(obj);
                let code = format!("{o}.{}({})", prop(&name), self.exprs(args));
                if self.an.async_keys.contains(&method_key(&strukt, &name)) {
                    self.await_(code)
                } else {
                    code
                }
            }
            CallKind::Dynamic => {
                let f = match &callee.kind {
                    ExprKind::Field { obj, name, .. } => {
                        let o = self.expr(obj);
                        format!("{o}.{}", prop(name))
                    }
                    _ => self.expr(callee),
                };
                let code = format!("{f}({})", self.exprs(args));
                self.await_(code)
            }
            CallKind::Builtin(name) => self.builtin(&name, e, args),
            CallKind::BuiltinMethod(recv, name) => {
                let ExprKind::Field { obj, .. } = &callee.kind else { return String::new() };
                let o = self.expr(obj);
                let mut a = self.exprs(args);
                if let (Recv::List, "join", Type::List(elem)) = (recv, name.as_str(), self.ty(obj)) {
                    if let Some(shape) = float_shape(&elem) {
                        a = format!("{a}, {shape}");
                    }
                }
                self.builtin_method(recv, &name, &o, &a)
            }
        }
    }

    fn builtin(&mut self, name: &str, e: &Expr, args: &[Expr]) -> String {
        match name {
            "print" => {
                let parts: Vec<String> = args.iter().map(|a| self.to_str(a)).collect();
                return format!("$rt.print({})", parts.join(", "));
            }
            "str" => return self.to_str(&args[0]),
            "expect" => {
                let loc = self.opts.sources.locate(e.span.start);
                let file = loc.file.rsplit(['/', '\\']).next().unwrap_or(loc.file);
                let place = format!("{file}:{}", loc.line);
                let cond = self.expr(&args[0]);
                return format!("$rt.expect({cond}, {})", js_string(&place));
            }
            _ => {}
        }
        let a = self.exprs(args);
        match name {
            "int" => format!("Math.trunc({a})"),
            "float" => a,
            "parse_int" => format!("$rt.parseInt_({a})"),
            "parse_float" => format!("$rt.parseFloat_({a})"),
            "read_file" => format!("$rt.readFile({a})"),
            "write_file" => format!("$rt.writeFile({a})"),
            "append_file" => format!("$rt.appendFile({a})"),
            "file_exists" => format!("$rt.fileExists({a})"),
            "args" => "$rt.args()".to_string(),
            "env" => format!("$rt.env({a})"),
            "exit" => format!("$rt.exit({a})"),
            "sleep" => self.await_(format!("$rt.sleep({a})")),
            "now" => "Date.now()".to_string(),
            "random" => "Math.random()".to_string(),
            "random_int" => format!("$rt.randomInt({a})"),
            "input" => format!("$rt.input({a})"),
            "fetch" => self.await_(format!("$rt.fetch_({a})")),
            "panic" => format!("$rt.panic({a})"),
            "sqrt" | "pow" | "floor" | "ceil" | "round" | "abs" | "min" | "max" => format!("Math.{name}({a})"),
            other => format!("$rt.panic(\"unknown builtin {other}\")"),
        }
    }

    fn builtin_method(&mut self, recv: Recv, name: &str, o: &str, a: &str) -> String {
        match (recv, name) {
            (Recv::Str, "len") | (Recv::List, "len") => format!("{o}.length"),
            (Recv::Str, "upper") => format!("{o}.toUpperCase()"),
            (Recv::Str, "lower") => format!("{o}.toLowerCase()"),
            (Recv::Str, "trim") => format!("{o}.trim()"),
            (Recv::Str, "split") => format!("$rt.split({o}, {a})"),
            (Recv::Str, "contains") => format!("{o}.includes({a})"),
            (Recv::Str, "starts_with") => format!("{o}.startsWith({a})"),
            (Recv::Str, "ends_with") => format!("{o}.endsWith({a})"),
            (Recv::Str, "replace") => format!("$rt.replace({o}, {a})"),
            (Recv::Str, "index_of") => format!("{o}.indexOf({a})"),
            (Recv::Str, "slice") | (Recv::List, "slice") => format!("{o}.slice({a})"),
            (Recv::Str, "chars") => format!("Array.from({o})"),
            (Recv::Str, "repeat") => format!("$rt.repeat({o}, {a})"),

            (Recv::List, "push") => format!("{o}.push({a})"),
            (Recv::List, "reverse") => format!("{o}.slice().reverse()"),
            (Recv::List, "clear") => format!("({o}.length = 0)"),
            (Recv::List, "pop" | "first" | "last" | "sort") => format!("$rt.list.{name}({o})"),
            (Recv::List, "contains" | "join" | "insert" | "remove") => format!("$rt.list.{name}({o}, {a})"),
            (Recv::List, "index_of") => format!("$rt.list.indexOf({o}, {a})"),
            (Recv::List, "map" | "filter") => self.await_(format!("$rt.list.{name}({o}, {a})")),
            (Recv::List, "sort_by") => self.await_(format!("$rt.list.sortBy({o}, {a})")),

            (Recv::Map, "len") => format!("{o}.size"),
            (Recv::Map, "get") => format!("$rt.mapTryGet({o}, {a})"),
            (Recv::Map, "has") => format!("{o}.has({a})"),
            (Recv::Map, "remove") => format!("{o}.delete({a})"),
            (Recv::Map, "keys") => format!("Array.from({o}.keys())"),
            (Recv::Map, "values") => format!("Array.from({o}.values())"),
            (Recv::Map, "clear") => format!("{o}.clear()"),

            (Recv::Chan, "close") => format!("{o}.close()"),
            _ => format!("$rt.panic(\"unknown method {name}\")"),
        }
    }
}

/// In JavaScript an int and a float are the same kind of number, so a value
/// alone does not tell whether `2` should be shown as `2` or `2.0`. Where
/// the type says that floats are involved, the runtime is told where they
/// are: `1` for a float, `[shape]` for a list of them, `{v: shape}` for the
/// values of a map. Structs carry this information themselves (`$floats`).
fn float_shape(ty: &Type) -> Option<String> {
    match ty {
        Type::Float => Some("1".to_string()),
        Type::List(elem) => float_shape(elem).map(|shape| format!("[{shape}]")),
        Type::Map(_, value) => float_shape(value).map(|shape| format!("{{v: {shape}}}")),
        _ => None,
    }
}
